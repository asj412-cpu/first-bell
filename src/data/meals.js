function withGuidance(item) {
  const note = GUIDANCE[item.id] ? { ...item, ...GUIDANCE[item.id] } : item
  const protein = note.proteinParts
    ? proteinFromParts(note.proteinParts)
    : note.proteinId
      ? proteinServing(note.proteinId, note.portionG, note.portionLabel)
      : null
  return {
    ...item,
    ...note,
    proteinAnchor: note.proteinAnchor || null,
    proteinGrams: protein ? protein.grams : null,
    proteinBasis: protein ? protein.basis : null,
    flavor: note.flavor || null,
    seasonalTheme: Boolean(note.seasonalTheme),
    refinedGrain: Boolean(note.refinedGrain),
    highlyProcessed: Boolean(note.highlyProcessed),
    pureeOk: Boolean(note.pureeOk),
    plan: note.plan !== false,
  }
}

